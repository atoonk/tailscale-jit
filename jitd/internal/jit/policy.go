// SnippetOptions shapes PolicySnippet.
type SnippetOptions struct {
	JITTag string
	// Policy, when known, marks each posture and grant as already in the
	// policy or new. Nil means unknown: nothing is marked.
	Policy *tsapi.Policy
	// OnlyMissing leaves out what the policy already has (needs Policy).
	OnlyMissing bool
	// Offline says the policy was not read at all (jitd -policy-snippet),
	// as opposed to a read that failed.
	Offline bool
}

// PolicySnippet renders the postures and grants an admin must merge into the
// tailnet policy file: one posture and one grant per approval flow, gating
// the flow's resources on its JIT posture attribute. jitd never edits the
// policy file itself.
func (s *Service) PolicySnippet(jitTag string) string {
	return s.Snippet(SnippetOptions{JITTag: jitTag, Offline: true})
}

// CheckedSnippet is PolicySnippet with the current policy file, so entries
// already in it are marked (or left out with onlyMissing). If the policy
// cannot be read the snippet is unmarked and the error is returned with it.
func (s *Service) CheckedSnippet(ctx context.Context, jitTag string, onlyMissing bool) (string, error) {
	opts := SnippetOptions{JITTag: jitTag}
	var err error
	if s.PolicyCache == nil {
		err = fmt.Errorf("no policy source configured")
	} else if opts.Policy, err = s.PolicyCache.Policy(ctx); err != nil {
		opts.Policy = nil
	}
	if opts.Policy != nil {
		opts.OnlyMissing = onlyMissing
	}
	return s.Snippet(opts), err
}

// Snippet renders the policy snippet with options.
func (s *Service) Snippet(o SnippetOptions) string {
	flows := s.ListWorkflows()
	// What the policy already has, per flow.
	type state struct {
		posture, grant bool
		use            *PolicyUse
	}
	states := map[string]state{}
	if o.Policy != nil {
		for _, w := range flows {
			u := policyUse(o.Policy, w)
			states[w.ID] = state{posture: u.Defined, grant: !u.Unreferenced, use: u}
		}
	}
	mark := func(have bool) string {
		if o.Policy == nil {
			return ""
		}
		if have {
			return " // already in your policy"
		}
		return " // NEW: not in your policy yet"
	}
	var postures, grants []*Workflow
	for _, w := range flows {
		st := states[w.ID]
		if !o.OnlyMissing || !st.posture {
			postures = append(postures, w)
		}
		if !o.OnlyMissing || !st.grant {
			grants = append(grants, w)
		}
	}

	var b strings.Builder
	b.WriteString("// Generated by jitd from its approval flows. Merge these into your tailnet policy file.\n")
	b.WriteString("//\n")
	switch {
	case o.Offline:
		b.WriteString("// (Not compared with your policy file; the Policy snippet page in jitd marks what you already have.)\n")
	case o.Policy == nil:
		b.WriteString("// (The policy file could not be read, so nothing is marked as already present.)\n")
	case o.OnlyMissing:
		b.WriteString("// Only what your policy does not have yet is shown.\n")
	default:
		b.WriteString("// Entries are marked \"already in your policy\" or \"NEW\" by comparing with the current policy file.\n")
	}
	b.WriteString("//\n")
	b.WriteString("// An approval sets the flow's posture attribute on the requester's device,\n")
	b.WriteString("// with an expiry; Tailscale removes it when the approval window ends. The\n")
	b.WriteString("// grant below is what that attribute unlocks: adjust its dst to the\n")
	b.WriteString("// resources the flow should give access to.\n")
	b.WriteString("//\n")
	b.WriteString("// For each destination, REMOVE any other grant that already gives the same\n")
	b.WriteString("// sources access to it; otherwise they have standing access and the JIT gate\n")
	b.WriteString("// changes nothing. Do not grant autogroup:member access to a PAM connector's\n")
	b.WriteString("// tag either: that makes every service on the connector visible.\n")
	b.WriteString("// srcPosture is not allowed with src \"*\", so sources are listed explicitly.\n")
	b.WriteString("{\n")

	b.WriteString("  \"postures\": {\n")
	if len(postures) == 0 {
		b.WriteString("    // all postures are already in your policy\n")
	}
	for i, w := range postures {
		fmt.Fprintf(&b, "    %s: [%s]%s%s\n", q(w.Posture()), q(w.Attribute+" == true"), comma(i, len(postures)), mark(states[w.ID].posture))
	}
	b.WriteString("  },\n\n")

	b.WriteString("  \"grants\": [\n")
	if len(grants) == 0 {
		b.WriteString("    // all flows already have a grant in your policy\n")
	}
	for _, w := range grants {
		st := states[w.ID]
		dst := w.ResourceNames()
		src := make([]string, len(w.Requesters))
		for i, p := range w.Requesters {
			src[i] = string(p)
		}
		fmt.Fprintf(&b, "    {\n")
		fmt.Fprintf(&b, "      // Approval flow %q%s\n", w.Name, strings.TrimPrefix(mark(st.grant), " //"))
		if st.grant && st.use != nil && (len(st.use.Missing) > 0 || len(st.use.Extra) > 0) {
			fmt.Fprintf(&b, "      // Your grant's dst differs from the flow's list: it has %s; the flow lists %s.\n", list(st.use.Grants), list(dst))
		}
		fmt.Fprintf(&b, "      \"src\": %s,\n", list(src))
		if len(dst) == 0 {
			fmt.Fprintf(&b, "      \"dst\": [\"TODO: what this flow gives access to (svc:..., tag:..., hosts)\"],\n")
		} else {
			fmt.Fprintf(&b, "      \"dst\": %s,\n", list(dst))
		}
		fmt.Fprintf(&b, "      \"ip\": [\"*\"],\n")
		fmt.Fprintf(&b, "      \"srcPosture\": [%s]\n", q(w.Posture()))
		fmt.Fprintf(&b, "      // For Tailscale PAM services, add the permissions here, e.g.\n")
		fmt.Fprintf(&b, "      // \"app\": {\"tailscale.com/cap/pam\": [{\"version\": \"v1\", \"permissions\": {...}}]}\n")
		fmt.Fprintf(&b, "    },\n")
	}
	jitGrant := o.Policy != nil && hasGrantTo(o.Policy, o.JITTag)
	if !o.OnlyMissing || !jitGrant {
		fmt.Fprintf(&b, "    {\n")
		fmt.Fprintf(&b, "      // Let tailnet members reach the jitd web UI and API.%s\n", strings.TrimPrefix(mark(jitGrant), " //"))
		fmt.Fprintf(&b, "      \"src\": [\"autogroup:member\"],\n")
		fmt.Fprintf(&b, "      \"dst\": [%s],\n", q(o.JITTag))
		ports := s.UIPorts
		if len(ports) == 0 {
			ports = []string{"tcp:80"}
		}
		fmt.Fprintf(&b, "      \"ip\": %s\n", list(ports))
		fmt.Fprintf(&b, "    }\n")
	} else {
		b.WriteString("    // the grant to " + o.JITTag + " is already in your policy\n")
	}
	b.WriteString("  ],\n\n")

	owned := false
	if o.Policy != nil {
		_, owned = o.Policy.TagOwners[o.JITTag]
	}
	if o.OnlyMissing && owned {
		fmt.Fprintf(&b, "  // tagOwners for %s is already in your policy\n", o.JITTag)
	} else {
		fmt.Fprintf(&b, "  // Needed once, so an auth key can be tagged %s.%s\n", o.JITTag, strings.TrimPrefix(mark(owned), " //"))
		fmt.Fprintf(&b, "  \"tagOwners\": {\n    %s: [\"autogroup:admin\"]\n  }\n", q(o.JITTag))
	}
	b.WriteString("}\n")
	return b.String()
}

// hasGrantTo reports whether any grant lists tag as a destination.
func hasGrantTo(p *tsapi.Policy, tag string) bool {
	for _, g := range p.Grants {
		if slices.Contains(g.Dst, tag) {
			return true
		}
	}
	return false
}

// PolicyUse is what the tailnet policy says about one flow's posture
// attribute: whether the posture exists, which grants use it and what they
// reach, and how that compares with the flow's "Gives access to" list.
type PolicyUse struct {
	Posture string `json:"posture"`
	// Defined: the posture exists and checks the flow's attribute.
	Defined bool `json:"defined"`
	// Grants are the destinations of every grant gated on the posture.
	Grants []string `json:"grants"`
	// Unreferenced: no grant uses the posture, so an approval unlocks nothing.
	Unreferenced bool `json:"unreferenced"`
	// Missing are listed resources no gated grant reaches; Extra are gated
	// destinations the flow does not list.
	Missing []string `json:"missing,omitempty"`
	Extra   []string `json:"extra,omitempty"`
	// Error is set when the policy could not be read; the other fields are
	// then unknown, not false.
	Error string `json:"error,omitempty"`
}

// OK reports whether the policy agrees with the flow.
func (u *PolicyUse) OK() bool {
	return u != nil && u.Error == "" && u.Defined && !u.Unreferenced && len(u.Missing) == 0 && len(u.Extra) == 0
}

// Problems lists what is wrong, for people.
func (u *PolicyUse) Problems() []string {
	var out []string
	if u == nil {
		return out
	}
	if u.Error != "" {
		return []string{u.Error}
	}
	switch {
	case u.Unreferenced && !u.Defined:
		out = append(out, fmt.Sprintf("not in the policy yet (no posture %s, no grant using it): approving unlocks nothing", u.Posture))
	case u.Unreferenced:
		out = append(out, "no grant uses the posture: approving unlocks nothing yet")
	case !u.Defined:
		out = append(out, fmt.Sprintf("a grant uses %s but the posture is not defined as %s == true", u.Posture, AttrPrefix+strings.TrimPrefix(u.Posture, "posture:jit_")))
	}
	if len(u.Missing) > 0 {
		out = append(out, "listed but not granted by the policy: "+strings.Join(u.Missing, ", "))
	}
	if len(u.Extra) > 0 {
		out = append(out, "granted by the policy but not listed: "+strings.Join(u.Extra, ", "))
	}
	return out
}

// PolicyUse checks the workflow against the tailnet policy. It never fails
// loudly: a policy that cannot be read is reported in Error.
func (s *Service) PolicyUse(ctx context.Context, w *Workflow) *PolicyUse {
	if s.PolicyCache == nil {
		return &PolicyUse{Posture: w.Posture(), Grants: []string{}, Error: "no policy source configured"}
	}
	p, err := s.PolicyCache.Policy(ctx)
	if err != nil {
		return &PolicyUse{Posture: w.Posture(), Grants: []string{}, Error: "could not read the policy file: " + err.Error()}
	}
	return policyUse(p, w)
}

// RequestPolicy is PolicyUse for the attribute and resources a request was
// filed with.
func (s *Service) RequestPolicy(ctx context.Context, r *AccessRequest) *PolicyUse {
	return s.PolicyUse(ctx, &Workflow{Attribute: r.Attribute, Resources: r.Resources})
}

// NoEffect reports whether approving would unlock nothing: the policy was
// read and has no posture or no grant for the attribute.
func (u *PolicyUse) NoEffect() bool {
	return u != nil && u.Error == "" && (u.Unreferenced || !u.Defined)
}

// policyUse is PolicyUse against an already fetched policy.
func policyUse(p *tsapi.Policy, w *Workflow) *PolicyUse {
	u := &PolicyUse{Posture: w.Posture(), Grants: []string{}}
	want := w.Attribute + " == true"
	for _, rule := range p.Postures[u.Posture] {
		if strings.Join(strings.Fields(rule), " ") == want {
			u.Defined = true
		}
	}
	used := false
	for _, g := range p.Grants {
		if !slices.Contains(g.SrcPosture, u.Posture) {
			continue
		}
		used = true
		for _, d := range g.Dst {
			if !slices.Contains(u.Grants, d) {
				u.Grants = append(u.Grants, d)
			}
		}
	}
	u.Unreferenced = !used
	slices.Sort(u.Grants)
	if used {
		for _, r := range w.Resources {
			if !slices.Contains(u.Grants, r.Name) {
				u.Missing = append(u.Missing, r.Name)
			}
		}
		for _, d := range u.Grants {
			if !slices.ContainsFunc(w.Resources, func(r Resource) bool { return r.Name == d }) {
				u.Extra = append(u.Extra, d)
			}
		}
	}
	return u
}

func q(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func list(ss []string) string {
	b, _ := json.Marshal(ss)
	return strings.ReplaceAll(string(b), "\",\"", "\", \"")
}

func comma(i, n int) string {
	if i < n-1 {
		return ","
	}
	return ""
}
